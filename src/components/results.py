"""
Results Component - Renders prediction results and reports
"""
import streamlit as st
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from ..config.settings import RISK_THRESHOLD_DEFAULT


def render_results(prob: float, pred: int, report_html: str, 
                  shap_df: pd.DataFrame = None, is_ai_report: bool = True):
    """
    Render the prediction results section
    
    Args:
        prob: Probability of default
        pred: Model prediction (0 or 1)
        report_html: HTML formatted report
        shap_df: DataFrame with SHAP values for plotting
        is_ai_report: Whether the report was generated by AI
    """
    st.markdown('<div class="thin-divider"></div>', unsafe_allow_html=True)
    
    # Determine verdict styling
    thresh = st.session_state.get("current_threshold", RISK_THRESHOLD_DEFAULT)
    review_thresh = thresh * 0.8
    
    if prob >= thresh:
        card_cls, verd_cls, verdict = "result-decline", "verdict-decline", "DECLINED"
    elif prob >= review_thresh:
        card_cls, verd_cls, verdict = "result-review", "verdict-review", "REQUIRES REVIEW"
    else:
        card_cls, verd_cls, verdict = "result-approve", "verdict-approve", "APPROVED"
    
    # Verdict card
    st.markdown(f"""
    <div class="result-card {card_cls}">
        <div style="display: flex; align-items: center; gap: 1rem;">
            <div>
                <div class="verdict-text {verd_cls}">{verdict}</div>
                <div style="color:#94a3b8;font-size:0.95rem;margin-top:0.3rem;">
                    Default Probability: <b style="color:#e2e8f0">{prob:.1%}</b>
                    &nbsp;|&nbsp; Model Decision: <b style="color:#e2e8f0">{'DEFAULT RISK' if pred==1 else 'LOW RISK'}</b>
                </div>
        </div>
    </div>
    """, unsafe_allow_html=True)
    
    # Probability bar
    _render_probability_bar(prob)
    
    # Two-column layout for Report + SHAP
    col_rep, col_shap = st.columns([3, 2])
    
    with col_rep:
        _render_report_section(report_html, is_ai_report)
    
    with col_shap:
        _render_shap_chart(shap_df)


def _render_probability_bar(prob: float):
    """Render the probability visualization bar"""
    fig_bar, ax_bar = plt.subplots(figsize=(8, 0.6))
    fig_bar.patch.set_facecolor("#111827")
    ax_bar.set_facecolor("#111827")
    
    thresh = st.session_state.get("current_threshold", RISK_THRESHOLD_DEFAULT)
    review_thresh = thresh * 0.8
    bar_color = "#ef4444" if prob >= thresh else (
        "#f59e0b" if prob >= review_thresh else "#22c55e"
    )
    
    ax_bar.barh(0, prob, color=bar_color, height=0.6)
    ax_bar.barh(0, 1 - prob, left=prob, color="#1e293b", height=0.6)
    ax_bar.set_xlim(0, 1)
    ax_bar.set_yticks([])
    ax_bar.tick_params(colors="#64748b", labelsize=8)
    ax_bar.spines[:].set_color("#1e293b")
    ax_bar.axvline(thresh, color="#475569", linestyle="--", linewidth=0.8)
    ax_bar.text(prob / 2, 0, f"{prob:.1%}", ha="center", va="center",
                color="white", fontsize=9, fontweight="bold")
    
    st.pyplot(fig_bar, use_container_width=True)
    plt.close(fig_bar)


def _render_report_section(report_html: str, is_ai_report: bool):
    """Render the AI credit report section"""
    badge_text = "Powered by GPT-4o" if is_ai_report else "Rule-Based Engine"
    
    st.markdown(f"""
        <div style="display: flex; align-items: center; justify-content: space-between; margin-bottom: 1rem;">
            <h4 style="margin: 0;">Credit Risk Report</h4>
            <span class="ai-badge">{badge_text}</span>
        </div>
    """, unsafe_allow_html=True)
    
    st.markdown(report_html, unsafe_allow_html=True)


def _render_shap_chart(shap_df: pd.DataFrame):
    """Render SHAP feature importance chart"""
    st.markdown("#### Model Explanation (SHAP)")
    
    if shap_df is not None and not shap_df.empty:
        fig_s, ax_s = plt.subplots(figsize=(5, 4.5))
        fig_s.patch.set_facecolor("#111827")
        ax_s.set_facecolor("#111827")
        
        colors = ["#ef4444" if v > 0 else "#22c55e" for v in shap_df["SHAP"]]
        ax_s.barh(
            shap_df["Feature"][::-1], 
            shap_df["SHAP"][::-1], 
            color=colors[::-1], 
            height=0.6
        )
        ax_s.axvline(0, color="#475569", linewidth=0.8)
        ax_s.tick_params(colors="#94a3b8", labelsize=7.5)
        ax_s.spines[:].set_color("#1e293b")
        ax_s.set_xlabel("SHAP Value", color="#64748b", fontsize=8)
        ax_s.set_title(
            "Red = increases risk  |  Green = reduces risk",
            color="#64748b", fontsize=7.5, pad=10
        )
        plt.tight_layout()
        st.pyplot(fig_s, use_container_width=True)
        plt.close(fig_s)
    else:
        st.info("SHAP explanation not available for this model type.")
